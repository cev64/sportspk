/**
 * Semantic colors that must stay meaningful regardless of the wallpaper-derived palette.
 * "Live" reading as green matters more than matching Material You.
 */
data class ScoreColors(val live: Color, val liveContainer: Color)

val LocalScoreColors = staticCompositionLocalOf {
    ScoreColors(live = LiveGreen, liveContainer = LiveGreenContainer)
}

@Composable
fun SportspkTheme(
    themeMode: ThemeMode = ThemeMode.SYSTEM,
    dynamicColor: Boolean = true,
    content: @Composable () -> Unit,
) {
    val darkTheme = when (themeMode) {
        ThemeMode.SYSTEM -> isSystemInDarkTheme()
        ThemeMode.LIGHT -> false
        ThemeMode.DARK -> true
    }

    val context = LocalContext.current
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S ->
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)

        darkTheme -> DarkColors
        else -> LightColors
    }

    val scoreColors = if (darkTheme) {
        ScoreColors(live = LiveGreenDark, liveContainer = LiveGreenContainerDark)
    } else {
        ScoreColors(live = LiveGreen, liveContainer = LiveGreenContainer)
    }

    CompositionLocalProvider(LocalScoreColors provides scoreColors) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = SportspkTypography,
            content = content,
        )
    }
}
